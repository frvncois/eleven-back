/**
 * Seeds Strapi from the front end's data/*.json, the one-time source of truth.
 * Run once against an empty database:  node scripts/seed.js
 *
 * Re-runnable: every content type is emptied first, so a second run replaces rather than duplicates.
 * Media is uploaded from eleven-front/public through a tmp copy, so the originals are never touched
 * (the upload service optimizes images in place).
 */
const fs = require("fs");
const os = require("os");
const path = require("path");

const FRONT = path.resolve(__dirname, "../../eleven-front");
const PUBLIC = path.join(FRONT, "public");

/**
 * The original hand-written content, frozen in scripts/seed-data/ at migration time.
 *
 * It deliberately does NOT read eleven-front/data/, because that directory is now generated by
 * eleven-front/scripts/pull-content.mjs — pointing the seed there would make it re-ingest its own
 * output (media paths already rewritten to Strapi URLs) and corrupt the content.
 */
const read = (f) => JSON.parse(fs.readFileSync(path.join(__dirname, "seed-data", f), "utf8"));

const MIME = { webp: "image/webp", png: "image/png", jpg: "image/jpeg", jpeg: "image/jpeg", gif: "image/gif", svg: "image/svg+xml", mp4: "video/mp4", webm: "video/webm", m4a: "audio/mp4", mp3: "audio/mpeg", wav: "audio/wav" };

// Layout geometry is not content: the wedge coordinates, the archive field, the room crops and the
// party placement all live in eleven-front/lib/layout.ts (and MixersBanner.tsx), joined to this
// content by slug or by order. Nothing here seeds a coordinate.

const COLLECTIONS = ["api::person.person", "api::project.project"];
const SINGLES = [
  "api::site-setting.site-setting",
  "api::home-page.home-page",
  "api::about-page.about-page",
  "api::legal-page.legal-page",
  "api::contact-page.contact-page",
  "api::archive-page.archive-page",
  "api::longform-page.longform-page",
  "api::party-mode.party-mode",
  "api::ui-label.ui-label",
];

async function main() {
  const { createStrapi, compileStrapi } = require("@strapi/strapi");
  const app = await createStrapi(await compileStrapi()).load();
  app.log.level = "error";

  const team = read("team.json");
  const projects = read("projects.json");
  const about = read("about.json");
  const site = read("site.json");
  const home = read("home.json");
  const legal = read("legal.json");
  const longform = read("longform.json");
  const party = read("party.json");
  const index = read("index.json");

  // ---------- media ----------
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "eleven-seed-"));
  const uploads = new Map(); // "/media/..." -> file id

  async function up(rel) {
    if (!rel) return null;
    if (uploads.has(rel)) return uploads.get(rel);
    const src = path.join(PUBLIC, rel);
    if (!fs.existsSync(src)) throw new Error(`missing media: ${rel}`);
    const name = path.basename(rel);
    const copy = path.join(tmp, `${uploads.size}-${name}`);
    fs.copyFileSync(src, copy);
    const ext = name.split(".").pop().toLowerCase();
    const [file] = await app.plugin("upload").service("upload").upload({
      data: { fileInfo: { name, folder: null } },
      files: { filepath: copy, originalFilename: name, mimetype: MIME[ext] || "application/octet-stream", size: fs.statSync(copy).size },
    });
    uploads.set(rel, file.id);
    return file.id;
  }

  // ---------- wipe ----------
  for (const uid of [...COLLECTIONS, ...SINGLES]) {
    const existing = await app.documents(uid).findMany({ status: "draft", fields: ["id"] });
    for (const doc of existing) await app.documents(uid).delete({ documentId: doc.documentId });
  }
  const oldFiles = await app.db.query("plugin::upload.file").findMany({ select: ["id"] });
  for (const f of oldFiles) await app.plugin("upload").service("upload").remove(await app.db.query("plugin::upload.file").findOne({ where: { id: f.id } }));
  console.log(`cleared ${COLLECTIONS.length + SINGLES.length} types, ${oldFiles.length} files`);

  const pub = (uid, data) => app.documents(uid).create({ data, status: "published" });
  const single = async (uid, data) => {
    const doc = await pub(uid, data);
    return doc;
  };

  // ---------- people ----------
  const teamRows = about.team.rows;
  const barOf = (slug) => {
    for (let row = 0; row < teamRows.length; row++) {
      const hit = teamRows[row].find((c) => c.slug === slug);
      if (hit) return { row, bar: hit };
    }
    throw new Error(`no team bar for ${slug}`);
  };

  const people = new Map(); // slug -> documentId
  const rowOf = new Map(); // slug -> row index
  for (const p of team) {
    const { row, bar } = barOf(p.slug);
    rowOf.set(p.slug, row);
    const doc = await pub("api::person.person", {
      slug: p.slug,
      name: p.name,
      role: p.role,
      email: p.email ?? null,
      instagram: p.instagram ?? null,
      linkedin: p.linkedin ?? null,
      isMixer: Boolean(p.isMixer),
      order: p.order,
      photo: await up(p.photo),
      icon: p.icon ? { name: p.icon.name, white: await up(p.icon.white), black: await up(p.icon.black) } : null,
      teamBar: { bg: bar.bg, ink: bar.ink, roles: bar.roles.map((label) => ({ label })) },
    });
    people.set(p.slug, doc.documentId);
  }
  console.log(`people: ${people.size}`);

  // ---------- projects ----------
  const tileOf = new Map(index.tiles.map((t, i) => [t.slug, { ...t, order: i }]));
  // `order` keeps each list's current sequence: spots within their mixer, longform among longform.
  const seq = new Map();
  const nextOrder = (key) => {
    const n = seq.get(key) ?? 0;
    seq.set(key, n + 1);
    return n;
  };

  const projectIds = new Map(); // slug -> documentId
  for (const p of projects) {
    const tile = tileOf.get(p.slug);
    if (!tile) throw new Error(`no archive tile for ${p.slug}`);
    const doc = await pub("api::project.project", {
      slug: p.slug,
      title: p.title,
      short: p.short ?? p.title,
      client: p.client,
      agency: p.agency ?? null,
      director: p.director ?? null,
      production: p.production ?? null,
      description: p.description ?? null,
      kind: p.kind,
      mixer: p.mixer ? people.get(p.mixer) : null,
      duration: p.duration,
      previewStart: p.previewStart ?? null,
      vimeo: p.vimeo,
      vimeoId: p.vimeoId,
      poster: await up(p.poster),
      onLanding: p.onLanding === true,
      order: nextOrder(p.kind === "spot" ? `spot:${p.mixer}` : "longform"),
      archiveTile: { order: tile.order, label: tile.title, clientLabel: tile.client },
    });
    projectIds.set(p.slug, doc.documentId);
  }
  console.log(`projects: ${projectIds.size}`);

  // ---------- site settings ----------
  const NAV_KEY = { Mixers: "mixers", Archive: "archive", Longform: "longform", About: "about", Contact: "contact" };
  await single("api::site-setting.site-setting", {
    nav: site.nav.map((n) => ({ key: NAV_KEY[n.label], label: n.label, href: n.href, match: n.match, color: n.color })),
    footer: {
      copyright: site.footer.copyright,
      legal: site.footer.legal.map((l) => ({ label: l.label, href: l.href })),
      creditsLabel: site.footer.credits.label,
      credits: site.footer.credits.items.map((c) => ({ name: c.name, role: c.role, href: c.href ?? null })),
      social: site.footer.social.map((s) => ({ platform: s.label.toLowerCase(), label: s.label, href: s.href })),
    },
    player: { play: site.player.play, pause: site.player.pause, close: site.player.close },
    seo: {
      defaultTitle: "Eleven",
      titleTemplate: "%s · Eleven",
      description: "Eleven is a boutique audio post-production studio in West LA since 1999. Mix, sound design, VO, ADR, music and voice casting. Good hangs, too.",
      siteName: "Eleven",
      locale: "en_US",
      themeColor: "#fdfcfc",
      ogImageAlt: fs.readFileSync(path.join(FRONT, "app/opengraph-image.alt.txt"), "utf8").trim(),
      twitterImageAlt: fs.readFileSync(path.join(FRONT, "app/twitter-image.alt.txt"), "utf8").trim(),
    },
  });

  // ---------- home ----------
  await single("api::home-page.home-page", {
    gate: { line1: home.gate.line[0], line2: home.gate.line[1], cursor: home.gate.cursor, skip: home.gate.skip, hint: home.gate.hint, tap: home.gate.tap },
    reel: { src: await up(home.reel.src), poster: await up(home.reel.poster) },
    reelPhone: { src: await up(home.reel.phone.src), poster: await up(home.reel.phone.poster) },
  });

  // ---------- about ----------
  const hotwords = (text) => [...text.matchAll(/\[\[(.+?)\]\]/g)].map((m) => m[1]);
  const services = [];
  for (const [name, note] of about.services.items) {
    const sounds = [];
    for (const word of hotwords(note)) {
      const files = about.services.sounds[word];
      if (!files) throw new Error(`service hotword with no sound: ${word}`);
      sounds.push({ word, files: await Promise.all(files.map(up)) });
    }
    services.push({ name, note, sounds });
  }

  const noteOf = async (n) =>
    n
      ? {
          n: n.n,
          text: n.text,
          photo: n.photo ? await up(n.photo.src) : null,
          photoAlt: n.photo?.alt ?? null,
        }
      : null;

  const storyParagraphs = [];
  for (const p of about.story.paragraphs) storyParagraphs.push({ text: p.text, note: await noteOf(p.note) });

  const rooms = [];
  for (const r of about.roomCarousel.items) rooms.push({ name: r.room, photo: await up(r.photo), preset: r.preset, audio: await up(r.audio) });

  await single("api::about-page.about-page", {
    storyIntro: about.story.intro,
    storyParagraphs,
    sticker: { image: await up(about.story.sticker.src), alt: null },
    globe: {
      image: await up(about.story.globe.src),
      alt: "Snow globe of the old Santa Monica studio",
      note: await noteOf(about.story.globe.note),
    },
    servicesLabel: about.services.label,
    services,
    teamLabel: about.team.label,
    teamMembers: team.map((p) => ({ person: people.get(p.slug), row: rowOf.get(p.slug) })),
    rooms,
    contactCta: { title: about.contact.title, line: about.contact.line, aside: about.contact.aside, cursor: about.contact.cursor, href: about.contact.href },
  });

  // ---------- legal ----------
  await single("api::legal-page.legal-page", {
    title: legal.title,
    sections: legal.sections.map((s) => ({
      sectionId: s.id,
      label: s.label,
      paragraphs: s.paragraphs.map((text) => ({ text })),
      note: s.note ?? null,
    })),
  });

  // ---------- contact ----------
  const c = site.contact;
  await single("api::contact-page.contact-page", {
    title: c.title,
    image: await up("/media/contact/steve-brule.gif"),
    imageAlt: "Dr. Steve Brule holding a microphone",
    people: c.people.map((p) => ({ name: p.name, role: p.role, email: p.email, phone: p.phone ?? null })),
    studio: { label: c.studio.label, line1: c.studio.lines[0], line2: c.studio.lines[1], map: c.studio.map, phone: c.studio.phone },
    repsLabel: c.reps.label,
    reps: c.reps.people.map((p) => ({ name: p.name, role: null, email: p.email, phone: p.phone ?? null })),
  });

  // ---------- archive ----------
  await single("api::archive-page.archive-page", { ariaLabel: "Archive, drag to explore" });

  // ---------- longform ----------
  await single("api::longform-page.longform-page", {
    films: longform.films.map((f) => {
      const id = projectIds.get(f.slug);
      if (!id) throw new Error(`longform film with no project: ${f.slug}`);
      return { project: id, label: f.label, color: f.color, objectPosition: f.position ?? null };
    }),
  });

  // ---------- party ----------
  const items = [];
  for (const i of party.items) {
    items.push({ image: await up(i.image), bg: i.bg, video: await up(i.video), audio: await up(i.audio) });
  }
  await single("api::party-mode.party-mode", { items, ariaLabel: "Easter egg", closeCursor: "close" });

  // ---------- ui labels ----------
  await single("api::ui-label.ui-label", {
    views: { list: "List", grid: "Grid", showAsTemplate: "Show as {view}" },
    dock: { menu: "Menu", close: "Close", sound: "Sound", on: "On", off: "Off" },
    gate: {
      soundAria: "Sound",
      skipAria: "Continue without sound",
      onAria: "Turn sound on",
      muteAria: "Mute sound",
      wordmarkAlt: "Eleven",
      soundLabel: "Sound",
      onLabel: "On",
      offLabel: "Off",
    },
    cursors: { play: "play", close: "close", listen: "listen", clickMe: "click me" },
    credits: {
      mixerTbc: "Mixer to confirm",
      roleMix: "Mix",
      roleMixSound: "Mix / Sound design",
      roleAgency: "Agency",
      roleProduction: "Production",
      roleDirector: "Director",
    },
    player: { seek: "Seek", nextFilm: "Next film", play: "Play", pause: "Pause" },
    regions: {
      main: "Main",
      projects: "Projects",
      films: "Films",
      mixers: "Mixers",
      closeMenu: "Close the menu",
      homeAria: "Eleven, home",
      homeGateAria: "Eleven, back to the sound gate",
      easterEgg: "Easter egg",
      archiveDrag: "Archive, drag to explore",
    },
    notFound: { title: "Sorry we lost you." },
    errorPage: { title: "Oops", body: "Something on this page went wrong.", cta: "Back to the homepage", retry: "Try again" },
  });

  fs.rmSync(tmp, { recursive: true, force: true });
  console.log(`singles: ${SINGLES.length}, media uploaded: ${uploads.size}`);
  await app.destroy();
  process.exit(0);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
